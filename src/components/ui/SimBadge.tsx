export type BadgeKind = 'simulated' | 'illustrative' | 'integration' | 'ai' | 'model' | 'llm' | 'live' | 'ondevice';

const TEXT: Record<BadgeKind, string> = {
  simulated: 'Simulated',
  illustrative: 'Illustrative',
  integration: 'Integration point',
  ai: 'Simulated AI',
  model: 'AI model',
  llm: 'Live AI',
  live: 'Live',
  ondevice: 'On-device AI',
};

const HINT: Record<BadgeKind, string> = {
  simulated: 'Simulated in the frontend. No live connection or real processing behind this.',
  illustrative: 'Illustrative figures only. Not measured or produced by a real system.',
  integration: 'Integration point: shown as a mock. Not connected to the real system.',
  ai: 'Scripted output standing in for an AI model. No model is called.',
  model: 'A trained model runs in the browser on the live data shown here. Its training history is generated until OQ RPI historical TA data is loaded.',
  llm: 'Answers are generated by a large language model that reads the live TURNPOINT data through tools.',
  live: 'Real call to an external system (read-only).',
  ondevice: 'Answers are composed on this device from the live TURNPOINT data. No language model is called.',
};

export function SimBadge({ kind = 'simulated', title }: { kind?: BadgeKind; title?: string }) {
  return (
    <span className={`sim-badge sim-${kind}`} title={title ?? HINT[kind]}>
      {TEXT[kind]}
    </span>
  );
}
